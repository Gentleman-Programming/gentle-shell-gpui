//! The credits kept in the repository's `CREDITS.md`, which Configuration ›
//! About shows: `## Heading` starts a group, `- Name (@login)` (or a bare
//! `- Name`) adds someone to it. Anything else, such as the title and its
//! note, is prose for people reading the file on GitHub and is skipped.

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Person {
    pub name: String,
    /// Their GitHub account, when the line names one.
    pub login: Option<String>,
}

impl Person {
    pub fn profile_url(&self) -> Option<String> {
        self.login
            .as_ref()
            .map(|login| format!("https://github.com/{login}"))
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Group {
    pub title: String,
    pub people: Vec<Person>,
}

/// The groups in file order, each with at least one person. A list before
/// the first heading belongs to no group and is skipped.
pub fn parse(text: &str) -> Vec<Group> {
    let mut groups: Vec<Group> = Vec::new();
    for line in text.lines().map(str::trim) {
        if let Some(title) = line.strip_prefix("## ") {
            groups.push(Group {
                title: title.trim().to_string(),
                people: Vec::new(),
            });
        } else if let (Some(item), Some(group)) = (
            line.strip_prefix("- ").or_else(|| line.strip_prefix("* ")),
            groups.last_mut(),
        ) {
            group.people.extend(person(item.trim()));
        }
    }
    groups.retain(|group| !group.people.is_empty());
    groups
}

/// `Name (@login)`; a login GitHub wouldn't accept leaves the whole text as
/// the name, so no link points somewhere unexpected.
fn person(item: &str) -> Option<Person> {
    let split = item
        .strip_suffix(')')
        .and_then(|rest| rest.rsplit_once("(@"))
        .map(|(name, login)| (name.trim(), login))
        .filter(|(name, login)| !name.is_empty() && valid_login(login));
    let (name, login) = match split {
        Some((name, login)) => (name, Some(login.to_string())),
        None => (item, None),
    };
    (!name.is_empty()).then(|| Person {
        name: name.to_string(),
        login,
    })
}

/// GitHub's rule: letters, digits and single inner hyphens, up to 39.
fn valid_login(login: &str) -> bool {
    !login.is_empty()
        && login.len() <= 39
        && !login.starts_with('-')
        && !login.ends_with('-')
        && !login.contains("--")
        && login
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-')
}

#[cfg(test)]
mod tests {
    use super::*;

    fn person(name: &str, login: Option<&str>) -> Person {
        Person {
            name: name.into(),
            login: login.map(Into::into),
        }
    }

    #[test]
    fn headings_group_the_people_listed_under_them() {
        let text = "# Credits\n\nSome prose, with - a dash.\n\n## Authors\n\n- Ada Lovelace (@ada)\n\n## Contributors\r\n* Grace Hopper (@grace-h)\r\n- Someone Offline\r\n";
        assert_eq!(
            parse(text),
            vec![
                Group {
                    title: "Authors".into(),
                    people: vec![person("Ada Lovelace", Some("ada"))],
                },
                Group {
                    title: "Contributors".into(),
                    people: vec![
                        person("Grace Hopper", Some("grace-h")),
                        person("Someone Offline", None),
                    ],
                },
            ]
        );
    }

    #[test]
    fn lists_outside_a_group_and_empty_groups_are_skipped() {
        let text = "- Stray (@stray)\n## Empty\n\n## Thanks\n- Linus (@torvalds)\n-\n";
        let groups = parse(text);
        assert_eq!(groups.len(), 1);
        assert_eq!(groups[0].title, "Thanks");
        assert_eq!(groups[0].people, vec![person("Linus", Some("torvalds"))]);
    }

    #[test]
    fn a_login_github_would_reject_stays_part_of_the_name() {
        for item in [
            "Bot (@dependabot[bot])",
            "Path (@../evil)",
            "Dash (@-x)",
            "Spaces (@two words)",
            "(@nameless)",
        ] {
            let people = person_of(item);
            assert_eq!(people.login, None, "{item}");
            assert_eq!(people.name, item, "{item}");
            assert_eq!(people.profile_url(), None, "{item}");
        }
        assert_eq!(
            person_of("Ana María (@ana-m)").profile_url().as_deref(),
            Some("https://github.com/ana-m")
        );
    }

    fn person_of(item: &str) -> Person {
        parse(&format!("## G\n- {item}\n"))
            .remove(0)
            .people
            .remove(0)
    }

    /// The file the app embeds (generated by `scripts/credits.sh`): a broken
    /// edit would empty the About page.
    #[test]
    fn the_repository_credits_link_every_contributor() {
        let groups = parse(include_str!("../../../CREDITS.md"));
        let titles: Vec<_> = groups.iter().map(|group| group.title.as_str()).collect();
        assert_eq!(titles, ["Contributors"]);
        for person in groups.iter().flat_map(|group| &group.people) {
            assert!(
                person.login.is_some(),
                "{} has no @login: add their address to .mailmap and run scripts/credits.sh",
                person.name
            );
        }
    }
}
